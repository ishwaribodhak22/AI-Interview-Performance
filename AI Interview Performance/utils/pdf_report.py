from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import inch
from datetime import datetime


def generate_pdf(
    candidate_name,
    interview_score,
    final_score,
    grammar_errors,
    filler_words,
    sentiment,
    feedback
):

    doc = SimpleDocTemplate(
        "Interview_Report.pdf",
        rightMargin=30,
        leftMargin=30,
        topMargin=30,
        bottomMargin=30
    )

    styles = getSampleStyleSheet()

    title_style = styles["Title"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.darkblue

    heading_style = styles["Heading2"]
    heading_style.textColor = colors.darkblue

    normal_style = styles["BodyText"]

    story = []

    # ==========================================
    # TITLE
    # ==========================================

    story.append(
        Paragraph(
            "AI INTERVIEW PERFORMANCE ANALYZER",
            title_style
        )
    )

    story.append(
        Paragraph(
            "<b>Professional Interview Report</b>",
            heading_style
        )
    )

    story.append(Spacer(1, 0.3 * inch))

    # ==========================================
    # DATE & TIME
    # ==========================================

    current_date = datetime.now().strftime("%d %B %Y")
    current_time = datetime.now().strftime("%I:%M %p")

    details = [
        ["Candidate Name", candidate_name],
        ["Date", current_date],
        ["Time", current_time]
    ]

    table = Table(details, colWidths=[160, 250])

    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (0,-1), colors.HexColor("#D6EAF8")),
        ("GRID", (0,0), (-1,-1), 1, colors.grey),
        ("FONTNAME", (0,0), (-1,-1), "Helvetica-Bold"),
        ("BOTTOMPADDING", (0,0), (-1,-1), 8)
    ]))

    story.append(table)

    story.append(Spacer(1, 0.3 * inch))

    # ==========================================
    # PERFORMANCE TABLE
    # ==========================================

    performance = [

        ["Metric", "Result"],

        ["Interview Score", f"{round(interview_score,2)} / 10"],

        ["Communication Score", f"{final_score} / 100"],

        ["Grammar Errors", str(grammar_errors)],

        ["Filler Words", str(filler_words)],

        ["Sentiment", sentiment]

    ]

    performance_table = Table(performance, colWidths=[220,180])

    performance_table.setStyle(TableStyle([

        ("BACKGROUND",(0,0),(-1,0),colors.darkblue),

        ("TEXTCOLOR",(0,0),(-1,0),colors.white),

        ("GRID",(0,0),(-1,-1),1,colors.black),

        ("BACKGROUND",(0,1),(-1,-1),colors.beige),

        ("ALIGN",(0,0),(-1,-1),"CENTER"),

        ("FONTNAME",(0,0),(-1,-1),"Helvetica-Bold"),

        ("BOTTOMPADDING",(0,0),(-1,-1),8)

    ]))

    story.append(performance_table)

    story.append(Spacer(1,0.4*inch))

    # ==========================================
    # AI FEEDBACK
    # ==========================================

    story.append(
        Paragraph(
            "<b>AI Suggestions</b>",
            heading_style
        )
    )

    story.append(Spacer(1,0.15*inch))

    for item in feedback:
        story.append(
            Paragraph(
                "✔ " + item,
                normal_style
            )
        )

    story.append(Spacer(1,0.4*inch))

    # ==========================================
    # OVERALL RESULT
    # ==========================================

    if final_score >= 90:
        result = "⭐⭐⭐⭐⭐ Outstanding"

    elif final_score >= 75:
        result = "⭐⭐⭐⭐ Excellent"

    elif final_score >= 60:
        result = "⭐⭐⭐ Good"

    elif final_score >= 40:
        result = "⭐⭐ Average"

    else:
        result = "⭐ Needs Improvement"

    story.append(
        Paragraph(
            "<b>Overall Performance</b>",
            heading_style
        )
    )

    story.append(
        Paragraph(
            result,
            normal_style
        )
    )

    story.append(Spacer(1,0.5*inch))

    # ==========================================
    # FOOTER
    # ==========================================

    footer = Paragraph(

        "<font color='grey'>"
        "<i>"
        "Generated by AI Interview Performance Analyzer<br/>"
        "Machine Learning + Natural Language Processing Project"
        "</i>"
        "</font>",

        styles["BodyText"]

    )

    story.append(footer)

    doc.build(story)